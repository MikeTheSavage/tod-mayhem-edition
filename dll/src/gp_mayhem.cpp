// gp_mayhem.cpp - [mayhem_title] of TODGameplay.dll: MAYHEM burns through the title screen under the TOTAL OVERDOSE
// logo, and into the main menu's header band after "TOTAL OVERDOSE".
//
// Title screen ("PRESS ENTER TO START"): for `delay` seconds it is exactly vanilla; then an ember ignites at the
// shotgun's muzzle and a ring of fire eats a hole through the picture over `reveal_seconds`: a thin hot rim, the paper
// curling back and browning just outside it, a dark scorch ahead, charred black-brown with dying ember specks behind.
// The hole's final shape hugs the lettering; MAYHEM comes up inside it dark -> glowing -> its own colours. Afterwards
// the painted flames shimmer (heat haze), the ember cracks flicker, a looping fire (flipbook from a real flame clip)
// licks over the flame tips and a few sparks rise. Main menu: the same burn the first time it appears in a session,
// already burnt in afterwards.
//
// Art (files next to the DLL, built by mayhem_title/art/build_*.py): TODGameplay_mayhem.dds (the MAYHEM
// lettering, premultiplied, mips), TODGameplay_mayhem_fx.dds (hole field / flame band / ember cracks / burn noise + the
// region's numbers in its header), TODGameplay_mayhem_fire.dds (the fire flipbook, DXT1). Per-pixel look: the pixel
// shader gp_mayhem_ps.hlsl (ps_3_0 + the vertex shader gp_mayhem_vs.hlsl), compiled by build.bat with fxc.
//
// When it draws (sites / references in sites.h, rows MT_*):
// (MT_SPRITE_VT / MT_EXEC_A / _B are the shared overlay hooks of dll/src/gp_overlay.cpp: this is a sprite client of the
// title picture and a list client for the caption's list; [minimap] / [mayhem_heat] use the same hooks)
//   MT_SPRITE_VT   Sprite vtable slot +20h (per-frame render) -> the overlay's SpriteWrap: the title picture (node "StartScreen",
//                  parent "StartScreenfolder") submitted its render list this frame
//   MT_TEXTBOX_VT  TextBox vtable slot +20h (TextBox render 0x8FE280) -> TextBoxWrap: the menu caption
//                  ("Caption_Yellow" in "GfxFolder") showing "TOTAL OVERDOSE" submitted its list this frame
//   MT_EXEC_A/_B   the list executor calls in the layer renderer -> the overlay's ExecWrap: right after such a list ran, the pass
// So whatever the game draws later stays on top, and nothing is drawn on any other screen. Device state: everything the
// overlay touches is read before and written back after (no state blocks). OFF by default in code.
