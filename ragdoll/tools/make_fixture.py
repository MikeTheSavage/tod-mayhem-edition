"""make_fixture.py - turns characters of a renderer-bridge bone probe (tod_bridge_probe.txt:
per bone parent, name, local position, stored quaternion and the game's own world matrix) into ragdoll/code/
rd_fixture.inc, the real skeleton data the ragdoll unit tests run on.
  python -I make_fixture.py PROBE OUT.inc HANDLE [HANDLE ...]"""
import re, sys

def parse(path):
    chars, cur = {}, None
    for line in open(path, encoding="utf-8", errors="replace"):
        if line.startswith("character "):
            t = line.split()
            h = int(t[1]); i = t.index("root")
            cur = chars.setdefault(h, {"root": [float(x) for x in t[i + 1:i + 17]], "bones": []})
        elif line.startswith("bone ") and cur is not None:
            m = re.match(r"bone (\d+) parent (-?\d+) name (.*?) local (\S+) (\S+) (\S+) stored (\S+) (\S+) (\S+) (\S+) world (.*)$", line.strip())
            if not m:
                continue
            g = m.groups()
            cur["bones"].append((int(g[0]), int(g[1]), g[2], [float(x) for x in g[3:6]], [float(x) for x in g[6:10]],
                                 [float(x) for x in g[10].split()]))
    return chars

def main():
    probe, out, hs = sys.argv[1], sys.argv[2], [int(x) for x in sys.argv[3:]]
    chars = parse(probe)
    f = ["// rd_fixture.inc - generated by ragdoll/tools/make_fixture.py from %s (real game data, do not edit)" % probe.replace("\\", "/")]
    for h in hs:
        c = chars[h]
        f.append("static const FxBone FX%d_BONES[] = {" % h)
        for b in c["bones"]:
            f.append('    {%d, %d, "%s", {%s}, {%s}, {%s}},' % (b[0], b[1], b[2], ", ".join("%.6ff" % v for v in b[3]),
                     ", ".join("%.6ff" % v for v in b[4]), ", ".join("%.6ff" % v for v in b[5])))
        f.append("};")
        f.append("static const float FX%d_ROOT[16] = {%s};" % (h, ", ".join("%.6ff" % v for v in c["root"])))
    f.append("static const FxChar FX_CHARS[] = {%s};" % ", ".join("{%d, FX%d_BONES, (int)(sizeof FX%d_BONES / sizeof FX%d_BONES[0]), FX%d_ROOT}" % (h, h, h, h, h) for h in hs))
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(f) + "\n")
    print("wrote", out, "characters", hs)

if __name__ == "__main__":
    main()
